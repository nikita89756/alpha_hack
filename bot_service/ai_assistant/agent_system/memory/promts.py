def build_user_prompt(dialogue: Sequence[Dict[str, str]]) -> str:
    """Build the user prompt with the dialogue to be analyzed."""

    lines = []
    role_map = {"assistant": "operator", "system": None, "user": "user", "operator": "operator"}
    for idx, msg in enumerate(dialogue):
        raw_role = (msg.get("role") or "operator").lower().strip()
        mapped = role_map.get(raw_role)
        if mapped is None:
            continue
        content = (msg.get("content") or "").replace("\n", " ").strip()
        lines.append(f"[{idx}] {mapped}: {content}")
    rendered_dialogue = "\n".join(lines)

    today_iso = datetime.now(timezone.utc).date().isoformat()

    return (
        "Ниже передан диалог пользователя с Copilot. Извлекай только устойчивые факты по правилам системного "
        "промпта. Работай строго с тем, что есть в диалоге.\n"
        f"TODAY_ISO: {today_iso}\n\n"
        "Диалог:\n"
        f"{rendered_dialogue}\n\n"
        "Требования к ответу:\n"
        "- Верни только JSON со свойством `candidates` (максимум 10 элементов).\n"
        "- Соблюдай маскирование приватных данных.\n"
        "- Не добавляй поясняющий текст до или после JSON.\n"
        '- Если знаний нет, верни {"candidates": []}.'
    )
